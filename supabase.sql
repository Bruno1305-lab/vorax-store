-- Execute no SQL Editor do Supabase.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  category text,
  price numeric(10,2) not null check (price >= 0),
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating int not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now(),
  unique(product_id,user_id)
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  items jsonb not null,
  total numeric(10,2) not null check(total >= 0),
  status text not null default 'pending',
  created_at timestamptz not null default now()
);
create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  message text not null check(length(message) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.reviews enable row level security;
alter table public.orders enable row level security;
alter table public.chat_messages enable row level security;

-- Cria perfil automaticamente no cadastro.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, display_name) values(new.id, coalesce(new.raw_user_meta_data->>'name',''));
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles where id = (select auth.uid()) and role = 'admin');
$$;

create policy "Public can view active products" on public.products for select using (active = true or public.is_admin());
create policy "Admins manage products" on public.products for all using (public.is_admin()) with check (public.is_admin());

create policy "Users read own profile" on public.profiles for select using (id = (select auth.uid()) or public.is_admin());
-- Não permita que clientes alterem o próprio campo role. A promoção a admin é manual no SQL Editor.

create policy "Public read reviews" on public.reviews for select using (true);
create policy "Signed-in users add own review" on public.reviews for insert to authenticated with check (user_id = (select auth.uid()));
create policy "Users update own review" on public.reviews for update using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create policy "Users read own orders" on public.orders for select to authenticated using (user_id = (select auth.uid()) or public.is_admin());
create policy "Users create own orders" on public.orders for insert to authenticated with check (user_id = (select auth.uid()));
create policy "Admins update orders" on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "Authenticated read chat" on public.chat_messages for select to authenticated using (true);
create policy "Users send own chat messages" on public.chat_messages for insert to authenticated with check (user_id = (select auth.uid()));
create policy "Admins moderate chat" on public.chat_messages for delete to authenticated using (public.is_admin());

